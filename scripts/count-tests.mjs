// Counts this repo's tests, per suite, into src/content/testCounts.generated.ts
// for the Projects section, so the numbers on the page are the real ones.
//
// - Vitest and Playwright are asked directly (`vitest list`, `playwright test
//   --list`), which counts what each runner would actually run, including
//   it.each / test.each expansions.
// - Cypress has no list command, so its specs are counted statically: one per
//   `it(`. That's only accurate while no Cypress test is generated in a loop
//   or by `.each`, so the script refuses to count a spec that does either.
//
// Run manually (npm run count:tests) or as part of `npm run build`. Like the
// other build scripts, it's non-fatal: a suite that can't be counted keeps its
// previously committed number, with a warning.
import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT_PATH = path.join(root, 'src/content/testCounts.generated.ts')
const tag = '[count-tests]'

const SUITES = [
  { id: 'vitest', label: 'Vitest + Testing Library', count: countVitest },
  { id: 'cypress-component', label: 'Cypress component', count: () => countCypress(['src'], '.cy.tsx') },
  { id: 'playwright', label: 'Playwright E2E', count: countPlaywright },
  { id: 'cypress-e2e', label: 'Cypress E2E', count: () => countCypress(['e2e/cypress'], '.cy.ts') },
]

function run(command, args) {
  const result = spawnSync(command, args, { cwd: root, encoding: 'utf8', shell: true, maxBuffer: 64 * 1024 * 1024 })
  if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} exited ${result.status}`)
  return result.stdout
}

// The JSON a runner prints can have log lines around it; take the outermost
// array or object.
function parseJsonFrom(output, open, close) {
  const start = output.indexOf(open)
  const end = output.lastIndexOf(close)
  if (start < 0 || end < start) throw new Error('no JSON in the output')
  return JSON.parse(output.slice(start, end + 1))
}

function countVitest() {
  const tests = parseJsonFrom(run('npx', ['vitest', 'list', '--json']), '[', ']')
  return tests.length
}

function countPlaywright() {
  const report = parseJsonFrom(run('npx', ['playwright', 'test', '--list', '--reporter=json']), '{', '}')
  let total = 0
  const walk = (suite) => {
    for (const spec of suite.specs ?? []) total += spec.tests.length
    for (const child of suite.suites ?? []) walk(child)
  }
  report.suites.forEach(walk)
  return total
}

function filesUnder(dir, suffix) {
  const full = path.join(root, dir)
  if (!existsSync(full)) return []
  return readdirSync(full, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(suffix))
    .map((entry) => path.join(entry.parentPath ?? entry.path, entry.name))
}

function countCypress(dirs, suffix) {
  let total = 0
  for (const file of dirs.flatMap((dir) => filesUnder(dir, suffix))) {
    const source = readFileSync(file, 'utf8')
    const name = path.relative(root, file)
    if (/\bit\.(each|only|skip)\b|\b(describe|context)\.(only|skip)\b/.test(source)) {
      throw new Error(`${name} uses .each/.only/.skip, which a static count can't follow`)
    }
    if (/^\s*it\(\s*`/m.test(source)) {
      throw new Error(`${name} has a test with a template-literal name, likely generated in a loop`)
    }
    total += (source.match(/^\s*it\(/gm) ?? []).length
  }
  return total
}

function previousCounts() {
  if (!existsSync(OUTPUT_PATH)) return {}
  const text = readFileSync(OUTPUT_PATH, 'utf8')
  const json = text.slice(text.indexOf('= ') + 2, text.lastIndexOf(' as const'))
  try {
    return Object.fromEntries(JSON.parse(json).suites.map((suite) => [suite.id, suite.count]))
  } catch {
    return {}
  }
}

const previous = previousCounts()
const suites = SUITES.map(({ id, label, count }) => {
  try {
    const value = count()
    console.log(`${tag} ${label}: ${value}`)
    return { id, label, count: value }
  } catch (error) {
    const kept = previous[id]
    console.warn(`${tag} ${label}: couldn't count (${error.message}) - keeping ${kept ?? 'nothing'}.`)
    return { id, label, count: kept ?? 0 }
  }
})

const data = { suites }
writeFileSync(
  OUTPUT_PATH,
  `// AUTO-GENERATED by scripts/count-tests.mjs. Do not hand-edit; run
// \`npm run count:tests\` (it also runs as part of \`npm run build\`).
export const testCounts = ${JSON.stringify(data, null, 2)} as const
`,
)
console.log(`${tag} wrote ${path.relative(root, OUTPUT_PATH)}`)
